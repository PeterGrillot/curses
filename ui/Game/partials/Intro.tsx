const FRAME_INTERVAL_MS = 600;

const IntroScreen = () => {
  const [frameIndex, setFrameIndex] = useState(0);
  const [frameIndex2, setFrameIndex2] = useState(0);

  useEffect(() => {
    const id = setInterval(() => {
      setFrameIndex((prev) => (prev + 1) % FRAMES.length);
    }, FRAME_INTERVAL_MS);

    return () => clearInterval(id);
  }, []);

  useEffect(() => {
    const id = setInterval(() => {
      setFrameIndex2((prev) => (prev + 1) % FRAMES_2.length);
    }, FRAME_INTERVAL_MS);

    return () => clearInterval(id);
  }, []);

  return (
    <>
      <pre className="iwtcot-banner">
        <code>{FRAMES[frameIndex]}</code>
      </pre>
      <pre className="iwtcot-banner">
        <code>{FRAMES_2[frameIndex2]}</code>
      </pre>
    </>
  );
};

export { IntroScreen };
